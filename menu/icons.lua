function Icons.dictionary(icon)
    return DICTIONARIES[icon] or 'commonmenu'
end

-- The sprite name for the icon, or '' for NONE and unknown icons.
function Icons.sprite(icon, selected)
    local pair = SPRITES[icon]
    if not pair then
        return ''
    end
    return selected and pair[2] or pair[1]
end

function Icons.size(icon)
    return SIZES[icon] or 38
end

-- r, g, b for the icon on a row that is highlighted or not, enabled or not.
function Icons.colour(icon, selected, enabled)
    if MONOCHROME[icon] then
        if selected then
            if enabled then
                return 0, 0, 0
            end
            return 50, 50, 50
        end
        if enabled then
            return 255, 255, 255
        end
        return 109, 109, 109
    end
    local globe = GLOBE_COLOURS[icon]
    if globe then
        local rgb = enabled and globe[1] or globe[2]
        return rgb[1], rgb[2], rgb[3]
    end
    if enabled then
        return 255, 255, 255
    end
    return 109, 109, 109
end

return Icons
